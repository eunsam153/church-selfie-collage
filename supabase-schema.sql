-- Run this in Supabase Dashboard > SQL Editor.
-- MVP note: this app uses Supabase anonymous sign-in. Anyone with the app URL can sign in
-- anonymously and participate in the shared project. Do not store sensitive/private photos here.
-- Enable Anonymous Sign-ins in Authentication > Providers (or Sign In / Providers).

create table if not exists public.church42_photos (
  id bigint generated by default as identity primary key,
  project_code text not null default 'church-42',
  segment_no integer not null check (segment_no between 1 and 42),
  storage_path text not null,
  user_id uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique (project_code, segment_no)
);

alter table public.church42_photos enable row level security;

drop policy if exists "Authenticated users can read church42 photos" on public.church42_photos;
create policy "Authenticated users can read church42 photos"
on public.church42_photos for select to authenticated using (true);

drop policy if exists "Authenticated users can add church42 photos" on public.church42_photos;
create policy "Authenticated users can add church42 photos"
on public.church42_photos for insert to authenticated with check (true);

drop policy if exists "Authenticated users can update church42 photos" on public.church42_photos;
create policy "Authenticated users can update church42 photos"
on public.church42_photos for update to authenticated using (true) with check (true);

-- Create a private storage bucket for uploaded photos.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('church-42-photos', 'church-42-photos', false, 10485760, array['image/jpeg','image/png'])
on conflict (id) do nothing;

drop policy if exists "Authenticated users can read church42 storage" on storage.objects;
create policy "Authenticated users can read church42 storage"
on storage.objects for select to authenticated using (bucket_id = 'church-42-photos');

drop policy if exists "Authenticated users can upload church42 storage" on storage.objects;
create policy "Authenticated users can upload church42 storage"
on storage.objects for insert to authenticated with check (bucket_id = 'church-42-photos');

drop policy if exists "Authenticated users can update church42 storage" on storage.objects;
create policy "Authenticated users can update church42 storage"
on storage.objects for update to authenticated using (bucket_id = 'church-42-photos') with check (bucket_id = 'church-42-photos');

